'app.post("/api/backup/cos-upload",async(req,res)=>{',
'  try{',
'    if(!isCosEnabled())return res.status(400).json({success:false,message:"COS未配置"});',
'    const list=listAllBackups();if(!list.length)return res.status(404).json({success:false,message:"无本地备份"});',
'    const lp=path.join(list[0].dir,list[0].name);',
'    const r=await uploadBackupToCos(lp,list[0].name);',
